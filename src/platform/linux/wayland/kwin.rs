/// The D-Bus name CursorPie owns, the path and the interface of its object.
pub(crate) const SERVICE: &str = "org.cursorpie.Wayland";
pub(crate) const PATH: &str = "/org/cursorpie/Wayland";
pub(crate) const IFACE: &str = "org.cursorpie.Wayland";
/// The name the script is loaded under (and unloaded by).
pub(crate) const PLUGIN: &str = "cursorpie-adapter";
/// The name of the global shortcut CursorPie invokes to make the script report.
pub(crate) const SHORTCUT: &str = "CursorPieSync";

/// The app id of CursorPie's own windows (the same as `x11::OWN_APP_ID`).
const OWN_APP_ID: &str = "cursorpie";

/// Most windows kept from one report, most outputs, longest string, largest coordinate, and the
/// largest report that is parsed at all.
pub(super) const MAX_WINDOWS: usize = 512;
pub(super) const MAX_OUTPUTS: usize = 32;
const MAX_STRING: usize = 256;
const MAX_COORD: f64 = 1.0e6;
const MAX_JSON: usize = 256 * 1024;

// ------------------------------------------------------------------------------------- the script

/// The script. `@NAME@` marks the few constants that are filled in; nothing else is spliced.
///
/// The property names are those of the KWin 6 scripting API (`workspace.stackingOrder`,
/// `workspace.activeWindow`, `window.frameGeometry`, `window.resourceClass`,
/// `window.desktopFileName`, `window.internalId`, `workspace.cursorPos`, `workspace.screens`). A
/// property a Plasma release does not have reads as `undefined` and leaves its field empty: the
/// report stays valid and the feature degrades (risk R3). Every number goes out as a number and the
/// pointer as text (`"x,y"`), because `callDBus` types a whole number and a fractional one
/// differently and the receiving side would see two signatures.
const SCRIPT: &str = r#"// CursorPie adapter for KWin. Generated by CursorPie, loaded at run time, never written to your
// KDE configuration. It reports the pointer and the window list to CursorPie over D-Bus and brings
// a window forward when told to. It reads nothing else.
var SERVICE = "@SERVICE@";
var PATH = "@PATH@";
var IFACE = "@IFACE@";
var armed = false;
var lastPointer = 0;
var lastReport = 0;

function skipped(w) {
    return !!(w.dock || w.desktopWindow || w.notification || w.criticalNotification ||
              w.onScreenDisplay || w.tooltip || w.popupWindow || w.dropdownMenu ||
              w.popupMenu || w.comboBox || w.dndIcon || w.splash);
}

function desktopOf(w) {
    // 0 = on every desktop
    try {
        return (w.desktops && w.desktops.length > 0) ? w.desktops[0].x11DesktopNumber : 0;
    } catch (e) {
        return 0;
    }
}

function snapshot() {
    var list = workspace.stackingOrder;
    var wins = [];
    // top-most first
    for (var i = list.length - 1; i >= 0 && wins.length < 400; i--) {
        var w = list[i];
        var g = w.frameGeometry;
        wins.push({
            id: String(w.internalId),
            cls: String(w.resourceClass || ""),
            name: String(w.resourceName || ""),
            df: String(w.desktopFileName || ""),
            x: g.x, y: g.y, w: g.width, h: g.height,
            min: !!w.minimized,
            skip: skipped(w),
            desk: desktopOf(w)
        });
    }
    var outs = [];
    try {
        var screens = workspace.screens;
        for (var j = 0; j < screens.length; j++) {
            var r = screens[j].geometry;
            outs.push({x: r.x, y: r.y, w: r.width, h: r.height});
        }
    } catch (e) {}
    var current = 0;
    try { current = workspace.currentDesktop.x11DesktopNumber; } catch (e) {}
    var active = "";
    try { active = workspace.activeWindow ? String(workspace.activeWindow.internalId) : ""; } catch (e) {}
    var p = workspace.cursorPos;
    return JSON.stringify({px: p.x, py: p.y, active: active, desk: current, wins: wins, outs: outs});
}

function apply(commands) {
    var parts = String(commands).split(";");
    for (var i = 0; i < parts.length; i++) {
        var c = parts[i];
        if (c === "arm") {
            armed = true;
        } else if (c === "disarm") {
            armed = false;
        } else if (c.indexOf("activate:") === 0) {
            var id = c.substring(9);
            var list = workspace.stackingOrder;
            for (var k = 0; k < list.length; k++) {
                if (String(list[k].internalId) === id) {
                    workspace.activeWindow = list[k];
                    break;
                }
            }
        }
    }
}

function report() {
    callDBus(SERVICE, PATH, IFACE, "Report", snapshot(), function (reply) {
        if (reply) {
            apply(reply);
        }
    });
}

function reportSoon() {
    var now = Date.now();
    if (now - lastReport < 200) {
        return;
    }
    lastReport = now;
    report();
}

registerShortcut("@SHORTCUT@", "CursorPie: sync with the pie", "", report);

try {
    workspace.cursorPosChanged.connect(function () {
        var now = Date.now();
        if (now - lastPointer < (armed ? 16 : 100)) {
            return;
        }
        lastPointer = now;
        var p = workspace.cursorPos;
        callDBus(SERVICE, PATH, IFACE, "Pointer", p.x + "," + p.y);
    });
} catch (e) {}

try { workspace.windowActivated.connect(reportSoon); } catch (e) {}
try { workspace.windowAdded.connect(reportSoon); } catch (e) {}
try { workspace.windowRemoved.connect(reportSoon); } catch (e) {}
try { workspace.stackingOrderChanged.connect(reportSoon); } catch (e) {}

report();
"#;

/// The script text, ready to be written to a file and loaded.
pub(crate) fn script_source() -> String {
    SCRIPT
        .replace("@SERVICE@", SERVICE)
        .replace("@PATH@", PATH)
        .replace("@IFACE@", IFACE)
        .replace("@SHORTCUT@", SHORTCUT)
}

// ------------------------------------------------------------------------------- what it reports

#[derive(Deserialize, Default)]
#[serde(default)]
struct RawSnapshot {
    px: Option<f64>,
    py: Option<f64>,
    active: String,
    desk: i64,
    wins: Vec<RawWindow>,
    outs: Vec<RawRect>,
}

#[derive(Deserialize, Default)]
#[serde(default)]
struct RawWindow {
    id: String,
    cls: String,
    name: String,
    df: String,
    x: f64,
    y: f64,
    w: f64,
    h: f64,
    min: bool,
    skip: bool,
    desk: i64,
}

#[derive(Deserialize, Default)]
#[serde(default)]
struct RawRect {
    x: f64,
    y: f64,
    w: f64,
    h: f64,
}

/// One window as KWin described it, after checking.
#[derive(Clone, Debug, PartialEq)]
pub(crate) struct WinInfo {
    /// KWin's `internalId`: what `activate:` is given back.
    pub id: String,
    pub class: String,
    pub instance: String,
    pub desktop_file: String,
    pub rect: ScreenRect,
    pub hidden: bool,
    pub skip: bool,
    /// The virtual desktop it is on; `None` = on all of them.
    pub desktop: Option<u32>,
}

/// What one report said.
#[derive(Clone, Debug, Default, PartialEq)]
pub(crate) struct Snapshot {
    pub pointer: Option<Point>,
    /// The `id` of the window that has the focus.
    pub active: Option<String>,
    /// The virtual desktop in front.
    pub desktop: Option<u32>,
    /// Top-most first.
    pub windows: Vec<WinInfo>,
    pub outputs: Vec<ScreenRect>,
}

pub(super) fn finite_in_range(v: f64) -> bool {
    v.is_finite() && v.abs() <= MAX_COORD
}

pub(super) fn clip(s: &str) -> String {
    s.chars().take(MAX_STRING).collect()
}

/// A window id as KWin writes it: a UUID, with or without braces. Anything else is not kept, so
/// whatever a caller of the D-Bus name sends can never become part of a command.
pub(crate) fn valid_id(id: &str) -> bool {
    (1..=64).contains(&id.len())
        && id
            .chars()
            .all(|c| c.is_ascii_hexdigit() || matches!(c, '-' | '{' | '}'))
}

pub(super) fn rect_of(x: f64, y: f64, w: f64, h: f64) -> Option<ScreenRect> {
    (finite_in_range(x)
        && finite_in_range(y)
        && finite_in_range(w)
        && finite_in_range(h)
        && w >= 0.0
        && h >= 0.0)
        .then_some(ScreenRect { x, y, w, h })
}

fn desktop_number(n: i64) -> Option<u32> {
    u32::try_from(n).ok().filter(|d| *d > 0)
}

/// The report in `text`; `None` if it is too large or is not what the script writes. Windows and
/// outputs that do not pass the checks are left out, the rest is kept.
pub(crate) fn parse_snapshot(text: &str) -> Option<Snapshot> {
    if text.len() > MAX_JSON {
        return None;
    }
    let raw: RawSnapshot = serde_json::from_str(text).ok()?;
    let pointer = match (raw.px, raw.py) {
        (Some(x), Some(y)) if finite_in_range(x) && finite_in_range(y) => Some(Point::new(x, y)),
        _ => None,
    };
    let windows = raw
        .wins
        .into_iter()
        .take(MAX_WINDOWS)
        .filter(|w| valid_id(&w.id))
        .filter_map(|w| {
            Some(WinInfo {
                rect: rect_of(w.x, w.y, w.w, w.h)?,
                id: w.id,
                class: clip(&w.cls),
                instance: clip(&w.name),
                desktop_file: clip(&w.df),
                hidden: w.min,
                skip: w.skip,
                desktop: desktop_number(w.desk),
            })
        })
        .collect();
    let outputs = raw
        .outs
        .into_iter()
        .take(MAX_OUTPUTS)
        .filter_map(|r| rect_of(r.x, r.y, r.w, r.h))
        .filter(|r| r.w > 0.0 && r.h > 0.0)
        .collect();
    Some(Snapshot {
        pointer,
        active: Some(raw.active).filter(|a| valid_id(a)),
        desktop: desktop_number(raw.desk),
        windows,
        outputs,
    })
}

/// The pointer in `"x,y"` (what the script sends between reports).
pub(crate) fn parse_pointer(text: &str) -> Option<Point> {
    if text.len() > 64 {
        return None;
    }
    let (x, y) = text.split_once(',')?;
    let (x, y) = (x.trim().parse::<f64>().ok()?, y.trim().parse::<f64>().ok()?);
    (finite_in_range(x) && finite_in_range(y)).then(|| Point::new(x, y))
}

// ------------------------------------------------------------------------------- app ids and hits

/// The app id of a window, the one the X11 backend gives the same app: the canonical desktop-entry
/// id when there is an entry for it, otherwise the lower-case desktop-file name or class. KWin's
/// desktop-file name comes first: for a native Wayland window it already is the desktop-entry id.
pub(crate) fn app_id_of(w: &WinInfo, index: Option<&Index>) -> Option<String> {
    if let Some(idx) = index
        && let Some(id) = idx.canonical(&[
            w.desktop_file.as_str(),
            w.class.as_str(),
            w.instance.as_str(),
        ])
    {
        return Some(id);
    }
    [&w.desktop_file, &w.class, &w.instance]
        .into_iter()
        .map(|n| desktop_entry::id_key(n))
        .find(|k| !k.is_empty())
}

/// Every name a window goes by, lower case: for [`toplevels::belongs_to`].
fn names_of(w: &WinInfo, index: Option<&Index>) -> Vec<String> {
    let mut names: Vec<String> = [&w.desktop_file, &w.class, &w.instance]
        .into_iter()
        .map(|n| desktop_entry::id_key(n))
        .collect();
    names.extend(app_id_of(w, index));
    names
}

impl Snapshot {
    /// The windows as the pure hit test wants them, top-most first.
    pub(crate) fn toplevels(&self, index: Option<&Index>) -> Vec<Toplevel> {
        self.windows
            .iter()
            .filter_map(|w| {
                let app = app_id_of(w, index)?;
                Some(Toplevel {
                    skip: w.skip || app == OWN_APP_ID,
                    app,
                    x: w.rect.x,
                    y: w.rect.y,
                    w: w.rect.w,
                    h: w.rect.h,
                    hidden: w.hidden,
                    desktop: w.desktop,
                })
            })
            .collect()
    }

    /// The app of the window under `p` (logical points, as KWin counts them).
    pub(crate) fn app_at(&self, p: Point, index: Option<&Index>) -> Option<String> {
        let list = self.toplevels(index);
        let i = toplevels::hit_test(&list, p.x, p.y, self.desktop)?;
        Some(list[i].app.clone())
    }

    /// The app in front.
    pub(crate) fn frontmost(&self, index: Option<&Index>) -> Option<String> {
        let active = self.active.as_deref()?;
        let w = self.windows.iter().find(|w| w.id == active)?;
        app_id_of(w, index)
    }

    /// The top-most window of the app `app` goes by (what the user typed: an id, a class, a
    /// program name), hidden or not, on any desktop.
    pub(crate) fn window_of(&self, app: &str, index: Option<&Index>) -> Option<&WinInfo> {
        let aliases = match index {
            Some(idx) => idx.aliases(app),
            None => vec![desktop_entry::name_key(app)],
        };
        self.windows
            .iter()
            .filter(|w| !w.skip)
            .find(|w| toplevels::belongs_to(&names_of(w, index), &aliases))
    }
}

// ---------------------------------------------------------------------------------------- state

/// The latest report.
static SNAPSHOT: RwLock<Option<Arc<Snapshot>>> = RwLock::new(None);
/// The latest pointer position and its number: the number goes up with every new one, so the mouse
/// loop knows an answer is new without comparing positions.
static POINTER: Mutex<(u64, Option<Point>)> = Mutex::new((0, None));
static POINTER_SEQ: AtomicU64 = AtomicU64::new(0);
/// What CursorPie asked the script to do, handed to it in the reply to its next report.
static COMMANDS: Mutex<Vec<String>> = Mutex::new(Vec::new());
/// The script is loaded and KWin answers (or, for another adapter, the compositor answers).
static LOADED: AtomicBool = AtomicBool::new(false);
/// The adapter of this session can say where the pointer is (Sway's cannot, see
/// `adapter::Adapter::knows_pointer`).
static KNOWS_POINTER: AtomicBool = AtomicBool::new(true);

/// Records a report and returns the commands waiting for the script (`""` if none): the reply of
/// the D-Bus method. A report that does not pass the checks is dropped, and the commands wait.
pub(crate) fn on_report(json: &str) -> String {
    let Some(snap) = parse_snapshot(json) else {
        return String::new();
    };
    publish(snap);
    take_commands()
}

/// Makes `snap` the latest report. Its pointer, if it has one, is a new pointer answer. The
/// adapters that read a compositor themselves (Hyprland, Sway) call this with what they built.
pub(crate) fn publish(snap: Snapshot) {
    if let Some(p) = snap.pointer {
        set_pointer(p);
    }
    *SNAPSHOT.write().unwrap_or_else(|e| e.into_inner()) = Some(Arc::new(snap));
}

/// Records a pointer position (`"x,y"`).
pub(crate) fn on_pointer(text: &str) {
    if let Some(p) = parse_pointer(text) {
        set_pointer(p);
    }
}

/// Records a pointer position as a new answer.
pub(crate) fn set_pointer(p: Point) {
    let seq = POINTER_SEQ.fetch_add(1, Ordering::Relaxed) + 1;
    *POINTER.lock().unwrap_or_else(|e| e.into_inner()) = (seq, Some(p));
}

/// The latest report, if there is one.
pub(crate) fn snapshot() -> Option<Arc<Snapshot>> {
    SNAPSHOT.read().unwrap_or_else(|e| e.into_inner()).clone()
}

/// The latest pointer position KWin reported and its number (see [`POINTER`]).
pub(crate) fn pointer() -> Option<(u64, Point)> {
    let (seq, p) = *POINTER.lock().unwrap_or_else(|e| e.into_inner());
    p.map(|p| (seq, p))
}

/// Queues a command for the script. The queue is short: a command that nobody collected is
/// dropped when more arrive.
pub(crate) fn queue(command: &str) {
    let mut q = COMMANDS.lock().unwrap_or_else(|e| e.into_inner());
    q.retain(|c| c != command);
    if q.len() >= 8 {
        q.remove(0);
    }
    q.push(command.to_string());
}

/// Takes the queued commands, joined with `;` (an id has no `;`, see [`valid_id`]).
pub(crate) fn take_commands() -> String {
    let mut q = COMMANDS.lock().unwrap_or_else(|e| e.into_inner());
    let out = q.join(";");
    q.clear();
    out
}

/// Whether the adapter works: the script is loaded and has reported.
pub(crate) fn running() -> bool {
    LOADED.load(Ordering::Relaxed) && snapshot().is_some()
}

/// Set by the D-Bus side when the script was loaded (`true`) or KWin went away (`false`).
#[cfg_attr(not(target_os = "linux"), allow(dead_code))]
pub(crate) fn set_loaded(loaded: bool) {
    LOADED.store(loaded, Ordering::Relaxed);
}

/// Records whether the adapter can say where the pointer is. Set once, when the adapter starts.
pub(crate) fn set_knows_pointer(knows: bool) {
    KNOWS_POINTER.store(knows, Ordering::Relaxed);
}

/// Whether the adapter can say where the pointer is. When it cannot, the app under the cursor is
/// taken to be the focused one (`backend::bundle_id_at`).
pub(crate) fn knows_pointer() -> bool {
    KNOWS_POINTER.load(Ordering::Relaxed)
}

/// Asks the adapter to report now. Does not wait.
pub(crate) fn request_sync() {
    #[cfg(target_os = "linux")]
    super::poller::request_sync();
}

/// Starts the adapter of this session (for KDE the D-Bus service and loading the script into KWin;
/// see `poller::start`). Does nothing off Linux.
pub(crate) fn start() {
    #[cfg(target_os = "linux")]
    super::poller::start();
}

/// Tells the script to report the pointer at full rate (`true`, while a hold runs) or at the idle
/// rate (`false`).
pub(crate) fn arm(on: bool) {
    queue(if on { "arm" } else { "disarm" });
    request_sync();
}

/// Brings the window `id` forward.
pub(crate) fn activate(id: &str) {
    if valid_id(id) {
        queue(&format!("activate:{id}"));
        request_sync();
    }
}

// ------------------------------------------------------------------------------------- the facade

/// What `backend.rs` asks in a Wayland session. Each answers `None` / `false` / empty when KWin has
/// not reported yet, so the caller can fall back to what XWayland knows.
#[cfg(target_os = "linux")]
fn index() -> Option<Arc<Index>> {
    super::super::x11::index()
}

/// The app in front.
#[cfg(target_os = "linux")]
pub(crate) fn frontmost() -> Option<String> {
    snapshot()?.frontmost(index().as_deref())
}

/// The app of the window under the logical point `p`.
#[cfg(target_os = "linux")]
pub(crate) fn app_at(p: Point) -> Option<String> {
    snapshot()?.app_at(p, index().as_deref())
}

/// Brings the window of `app` forward; `false` if it has none (or KWin has not reported).
#[cfg(target_os = "linux")]
pub(crate) fn raise(app: &str) -> bool {
    let Some(snap) = snapshot() else {
        return false;
    };
    let Some(w) = snap.window_of(app, index().as_deref()) else {
        return false;
    };
    activate(&w.id);
    true
}

/// For each app id, whether it has a window (hidden ones count).
#[cfg(target_os = "linux")]
pub(crate) fn running_among(ids: &[Option<String>]) -> Vec<bool> {
    let snap = snapshot();
    let idx = index();
    ids.iter()
        .map(|id| match (&snap, id) {
            (Some(s), Some(id)) => s.window_of(id, idx.as_deref()).is_some(),
            _ => false,
        })
        .collect()
}

/// The outputs, in logical points.
pub(crate) fn displays() -> Vec<ScreenRect> {
    snapshot().map(|s| s.outputs.clone()).unwrap_or_default()
}

