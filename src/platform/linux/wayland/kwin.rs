    #[test]
    fn a_published_snapshot_is_the_latest_and_its_pointer_is_a_new_answer() {
        let _g = TEST_SERIAL.lock().unwrap_or_else(|e| e.into_inner());
        set_pointer(Point::new(1.0, 1.0));
        let before = pointer().unwrap().0;
        publish(Snapshot {
            pointer: Some(Point::new(7.0, 8.0)),
            active: Some(ID_A.to_string()),
            ..Snapshot::default()
        });
        let (seq, p) = pointer().unwrap();
        assert!(seq > before);
        assert_eq!(p, Point::new(7.0, 8.0));
        assert_eq!(
            snapshot().unwrap().active.as_deref(),
            Some(ID_A),
            "the snapshot is the one published"
        );
        // a snapshot with no pointer leaves the last answer alone
        publish(Snapshot::default());
        assert_eq!(pointer().unwrap(), (seq, Point::new(7.0, 8.0)));
    }

