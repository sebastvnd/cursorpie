//! The KDE Plasma adapter: where the pointer is, which windows there are, which app is under the
//! pointer, and bringing a window forward. KWin is the only one that knows, and a Wayland client
//! cannot ask it directly (`docs/WAYLAND_SUPPORT.md`, "Research"), so a small script runs *inside*
//! KWin and talks to CursorPie over D-Bus.
//!
//! This file is the pure part and the state, built and tested on every OS:
//!
//! * [`script_source`]: the text of the script. It does four things and nothing else: report the
//!   pointer, report the window list, activate a window by id when told to, and report the outputs.
//!   It is generated text with no user-supplied string in it (decision D4, risk R5).
//! * [`parse_snapshot`] / [`parse_pointer`]: what the script reports, **range checked**: any program
//!   of the same user can call CursorPie's D-Bus name, so every number is bounded, every string is
//!   clipped and every id is checked before it is kept.
//! * The window hit test, the app id of a window and "raise the window of this app", on the
//!   existing pure helpers (`toplevels`, `desktop_entry`), so one profile matches an app in both
//!   an X11 and a Wayland session.
//! * The global state the D-Bus service writes and the facade reads.
//!
//! The D-Bus half is `bus.rs`, built on Linux only.
//!
//! **The state is shared.** The other adapters (GNOME, Hyprland, Sway: `adapter.rs`) fill the same
//! state with the same [`Snapshot`] ([`publish`], [`set_pointer`]) and are told the same commands
//! ([`take_commands`]), so `backend.rs` asks one place whatever the compositor is. The name of this
//! file is the history of the code, not a limit.
//!
//! **How a question is answered.** The script reports on its own when the pointer moves (at most
//! every 100 ms, every 16 ms while a hold is armed) and when the windows change, and again when
//! CursorPie asks (a global shortcut CursorPie invokes). A reply to a report carries the commands
//! CursorPie queued (`arm`, `disarm`, `activate:<id>`). Nothing here blocks: the tap thread reads
//! the latest answer and never waits for a new one.

