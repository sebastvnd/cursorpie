    #[test]
    fn the_board_lives_through_a_whole_task() {
        let root = scratch("flow");
        let at = 1_795_689_600;
        let run = |command: Command| apply(&root, &command, at, "Ada").unwrap();

        assert!(
            problems(&root).unwrap().is_empty(),
            "no card and no board is in order"
        );

        let add_docs = words(&["add", "Write the docs", "--note", "Start here"]);
        let added = run(parse_args(&add_docs).unwrap());
        assert_eq!(added.text, "Added card 0001 to Backlog: Write the docs\n");
        assert_eq!(
            added.subject.as_deref(),
            Some("Add kanban card 0001: Write the docs")
        );
        run(parse_args(&words(&[
            "add", "Ship it", "--status", "done", "--owner", "Bo",
        ]))
        .unwrap());

        let moved = run(parse_args(&words(&["move", "1", "in-progress"])).unwrap());
        assert_eq!(
            moved.subject.as_deref(),
            Some("Move kanban card 0001 to In Progress")
        );
        let same = run(parse_args(&words(&["move", "1", "progress"])).unwrap());
        assert!(same.subject.is_none() && same.text.contains("already"));
        run(parse_args(&words(&["note", "1", "Half", "done"])).unwrap());

        let card_text = run(Command::Show { id: 1 }).text;
        assert!(card_text.contains("status: in-progress"));
        assert!(card_text.contains("owner: Ada"));
        assert!(card_text.contains("- 2026-11-26 10:40 UTC (Ada): Start here\n"));
        assert!(card_text.contains("(Ada): Moved from Backlog to In Progress\n"));
        assert!(card_text.contains("(Ada): Half done\n"));

        let board = fs::read_to_string(root.join("kanban/BOARD.md")).unwrap();
        assert!(board.contains("Backlog: 0, In Progress: 1, Done: 1, In Evaluation: 0"));
        assert!(!run(Command::Check).failed);

        // a card edited by hand leaves the board out of date, and `board` puts it right
        let path = root.join("kanban/cards/0002.md");
        let before = fs::read_to_string(&path).unwrap();
        let edited = before.replace("status: done", "status: in-evaluation");
        fs::write(&path, edited).unwrap();
        let check = run(Command::Check);
        assert!(
            check.failed && check.text.contains("out of date"),
            "{}",
            check.text
        );
        run(Command::Board);
        assert!(!run(Command::Check).failed);

        let removed = run(Command::Remove {
            id: 2,
            commit: false,
        });
        assert_eq!(removed.subject.as_deref(), Some("Remove kanban card 0002"));
        assert!(apply(&root, &Command::Show { id: 2 }, at, "").is_err());
        let note = Command::Note {
            id: 9,
            text: "x".to_string(),
            commit: false,
        };
        assert!(apply(&root, &note, at, "").is_err());
        assert_eq!(load_cards(&root).unwrap().len(), 1);
        let _ = fs::remove_dir_all(&root);
    }

