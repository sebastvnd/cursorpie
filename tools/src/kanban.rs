//! `cargo tools kanban`: the work board of the repository, kept in Git.
//!
//! The board has four columns: **Backlog**, **In Progress**, **Done** and **In Evaluation**. Every
//! card is one small Markdown file in `kanban/cards/` (`0001.md`, `0002.md`, ...), so the board
//! travels with the code: it is reviewed in pull requests, branched, merged and read in `git log`
//! like any other file, and nothing outside the repository is needed.
//!
//! ```text
//! ---
//! title: Fix double-click replay on slow clicks
//! status: in-progress
//! owner: Ada
//! created: 2026-11-26
//! updated: 2026-11-27
//! ---
//!
//! ## Notes
//!
//! - 2026-11-26 10:15 UTC (Ada): Reproduced with a 400 ms click gap.
//! ```
//!
//! `kanban/BOARD.md` is generated from the cards: four Markdown tables, one per column, readable
//! on GitHub. Every command that changes a card writes it again, and `cargo tools kanban check`
//! (a step of `cargo tools ci --quick`) fails when it is out of date, for instance after a card
//! was edited by hand. After a merge conflict in it, run `cargo tools kanban board`.
//!
//! | Command | What it does |
//! |---|---|
//! | `kanban [list [STATUS]]` | prints the board |
//! | `kanban show ID` | prints one card with its notes |
//! | `kanban add TITLE` | adds a card (`--status`, `--owner`, `--note`) |
//! | `kanban move ID STATUS` | moves a card to another column and writes a note about it |
//! | `kanban note ID TEXT` | appends a dated note to a card |
//! | `kanban rm ID` | deletes a card |
//! | `kanban board` | writes `kanban/BOARD.md` again |
//! | `kanban check` | verifies that the cards can be read and the board is up to date |
//!
//! `add`, `move`, `note` and `rm` take `--commit`: the change to `kanban/` (and nothing else) is
//! committed with a subject that follows the commit message rules of the project. Times are UTC.
//! The owner is `--owner`, or else `git config user.name`.
//!
//! The decisions (reading and writing a card, notes, the board, the dates) are pure functions with
//! unit tests; only `apply` and `run` touch the disk and Git.

use std::fs;
use std::io::ErrorKind;
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::time::{SystemTime, UNIX_EPOCH};

use crate::git::git;

/// The folder of the board, relative to the repository root.
const DIR: &str = "kanban";
/// The folder of the cards, inside [`DIR`].
const CARDS: &str = "cards";
/// The generated board, inside [`DIR`].
const BOARD: &str = "BOARD.md";
/// The heading under which the notes of a card are collected.
const NOTES_HEADING: &str = "## Notes";
/// The longest title of a card; what does not fit belongs in a note.
const MAX_TITLE_CHARS: usize = 100;
/// The longest subject of a commit, the limit of `commit_msg.rs`.
const MAX_SUBJECT_CHARS: usize = 72;
/// The lines a card may have between its two `---` lines.
const KNOWN_FIELDS: [&str; 5] = ["title", "status", "owner", "created", "updated"];

/// What `BOARD.md` starts with.
const BOARD_HEADER: &str = "\
# Kanban board

<!-- Generated by `cargo tools kanban board`. Do not edit it by hand: change the cards in
kanban/cards/ and run the command again. -->

";

/// The column of a card. The order of [`Status::ALL`] is the order of the columns on the board.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    /// Waiting: not started.
    Backlog,
    /// Somebody is working on it.
    InProgress,
    /// The work is finished.
    Done,
    /// The result is being evaluated.
    InEvaluation,
}

impl Status {
    /// Every column, left to right.
    pub const ALL: [Self; 4] = [
        Self::Backlog,
        Self::InProgress,
        Self::Done,
        Self::InEvaluation,
    ];

    /// The word written in a card file and typed on the command line.
    pub fn key(self) -> &'static str {
        match self {
            Self::Backlog => "backlog",
            Self::InProgress => "in-progress",
            Self::Done => "done",
            Self::InEvaluation => "in-evaluation",
        }
    }

    /// The name shown on the board.
    pub fn label(self) -> &'static str {
        match self {
            Self::Backlog => "Backlog",
            Self::InProgress => "In Progress",
            Self::Done => "Done",
            Self::InEvaluation => "In Evaluation",
        }
    }

    /// Reads a column from a word: its key or its name in any case, `progress` for `in-progress`,
    /// `evaluation` for `in-evaluation`, and a few other short forms.
    pub fn parse(word: &str) -> Option<Self> {
        let word = word.trim().to_lowercase().replace([' ', '_'], "-");
        match word.as_str() {
            "backlog" => Some(Self::Backlog),
            "in-progress" | "progress" | "doing" | "wip" => Some(Self::InProgress),
            "done" => Some(Self::Done),
            "in-evaluation" | "evaluation" | "evaluating" | "eval" => Some(Self::InEvaluation),
            _ => None,
        }
    }
}

/// One card of the board, as it is kept in its file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Card {
    /// The number; the file is `cards/NNNN.md`.
    pub id: u32,
    /// What the work is, on one line.
    pub title: String,
    /// The column.
    pub status: Status,
    /// Who works on it; empty when nobody does.
    pub owner: String,
    /// The day the card was added (`YYYY-MM-DD`, UTC).
    pub created: String,
    /// The day of the last change.
    pub updated: String,
    /// Free Markdown below the header, the notes included. Empty, or ends with a newline.
    pub body: String,
}

impl Card {
    /// How many notes the card holds: the list items of its body.
    pub fn notes(&self) -> usize {
        self.body.lines().filter(|l| l.starts_with("- ")).count()
    }
}

/// The file name of card `id`.
pub fn card_file_name(id: u32) -> String {
    format!("{id:04}.md")
}

/// The number in a card file name, `None` when the name is not that of a card.
fn id_from_file_name(name: &str) -> Option<u32> {
    let stem = name.strip_suffix(".md")?;
    if stem.is_empty() || !stem.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    stem.parse().ok()
}

/// Collapses every run of white space (new lines included) into one space.
fn clean_text(raw: &str) -> String {
    raw.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// A title as it is stored: one line, not empty, not longer than [`MAX_TITLE_CHARS`].
fn clean_title(raw: &str) -> Result<String, String> {
    let title = clean_text(raw);
    if title.is_empty() {
        return Err("the title is empty".to_string());
    }
    if title.chars().count() > MAX_TITLE_CHARS {
        return Err(format!(
            "the title is longer than {MAX_TITLE_CHARS} characters: keep it short and put the \
             details in a note"
        ));
    }
    Ok(title)
}

/// A new card without notes.
///
/// # Errors
/// When the title is empty or too long.
pub fn new_card(
    id: u32,
    title: &str,
    status: Status,
    owner: &str,
    date: &str,
) -> Result<Card, String> {
    Ok(Card {
        id,
        title: clean_title(title)?,
        status,
        owner: clean_text(owner),
        created: date.to_string(),
        updated: date.to_string(),
        body: String::new(),
    })
}

/// Appends a dated note to the end of the card, under the `## Notes` heading (which is added the
/// first time). `stamp` is the time as [`date_time`] writes it, `who` may be empty.
///
/// # Errors
/// When the note is empty.
pub fn add_note(card: &mut Card, stamp: &str, who: &str, text: &str) -> Result<(), String> {
    let text = clean_text(text);
    if text.is_empty() {
        return Err("the note is empty".to_string());
    }
    if !card.body.contains(NOTES_HEADING) {
        if !card.body.is_empty() {
            card.body.push('\n');
        }
        card.body.push_str(NOTES_HEADING);
        card.body.push_str("\n\n");
    }
    let who = clean_text(who);
    card.body.push_str("- ");
    card.body.push_str(stamp);
    if !who.is_empty() {
        card.body.push_str(" (");
        card.body.push_str(&who);
        card.body.push(')');
    }
    card.body.push_str(": ");
    card.body.push_str(&text);
    card.body.push('\n');
    Ok(())
}

/// Appends `key: value` and a new line.
fn field(out: &mut String, key: &str, value: &str) {
    out.push_str(key);
    out.push_str(": ");
    out.push_str(value);
    out.push('\n');
}

/// The text of the file of a card.
pub fn render_card(card: &Card) -> String {
    let mut out = String::from("---\n");
    field(&mut out, "title", &card.title);
    field(&mut out, "status", card.status.key());
    if !card.owner.is_empty() {
        field(&mut out, "owner", &card.owner);
    }
    field(&mut out, "created", &card.created);
    field(&mut out, "updated", &card.updated);
    out.push_str("---\n");
    if !card.body.is_empty() {
        out.push('\n');
        out.push_str(&card.body);
    }
    out
}

/// Reads the text of the file of card `id`.
///
/// # Errors
/// When the header is not between two `---` lines, a line of it is not `key: value`, a line has
/// an unknown key, or `title`, `status`, `created` or `updated` is missing or wrong.
pub fn parse_card(id: u32, text: &str) -> Result<Card, String> {
    let text = text.replace("\r\n", "\n");
    let mut lines = text.split('\n');
    if lines.next() != Some("---") {
        return Err("the file must start with a line of three dashes".to_string());
    }
    let mut fields: Vec<(String, String)> = Vec::new();
    let mut closed = false;
    for line in lines.by_ref() {
        if line == "---" {
            closed = true;
            break;
        }
        if line.trim().is_empty() {
            continue;
        }
        let (key, value) = line
            .split_once(':')
            .ok_or_else(|| format!("the line '{line}' is not of the form key: value"))?;
        let key = key.trim();
        if !KNOWN_FIELDS.contains(&key) {
            return Err(format!(
                "unknown line '{key}' (known: title, status, owner, ...)"
            ));
        }
        fields.push((key.to_string(), value.trim().to_string()));
    }
    if !closed {
        return Err("the header is not closed by a second line of three dashes".to_string());
    }
    let get = |key: &str| {
        fields
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, v)| v.clone())
    };
    let need = |key: &str| {
        get(key)
            .filter(|v| !v.is_empty())
            .ok_or_else(|| format!("the '{key}' line is missing or empty"))
    };
    let status_word = need("status")?;
    let status = Status::parse(&status_word).ok_or_else(|| {
        format!("unknown status '{status_word}': use backlog, in-progress, done or in-evaluation")
    })?;
    let rest: Vec<&str> = lines.collect();
    let joined = rest.join("\n");
    let trimmed = joined.trim_start_matches('\n').trim_end();
    let body = if trimmed.is_empty() {
        String::new()
    } else {
        format!("{trimmed}\n")
    };
    Ok(Card {
        id,
        title: need("title")?,
        status,
        owner: get("owner").unwrap_or_default(),
        created: need("created")?,
        updated: need("updated")?,
        body,
    })
}

/// The number for the next card: one more than the highest.
pub fn next_id(cards: &[Card]) -> u32 {
    cards.iter().map(|c| c.id).max().map_or(1, |m| m + 1)
}

/// Makes a text safe for a cell of a Markdown table.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// One row of a table of the board.
fn row(card: &Card) -> String {
    let id = card.id;
    let title = cell(&card.title);
    let owner = if card.owner.is_empty() {
        "-".to_string()
    } else {
        cell(&card.owner)
    };
    let updated = &card.updated;
    let notes = card.notes();
    format!("| [{id:04}]({CARDS}/{id:04}.md) | {title} | {owner} | {updated} | {notes} |\n")
}

/// The text of `BOARD.md`: one table per column, in the order of [`Status::ALL`], cards by number.
pub fn render_board(cards: &[Card]) -> String {
    let mut out = String::from(BOARD_HEADER);
    let mut summary: Vec<String> = Vec::new();
    for status in Status::ALL {
        let count = cards.iter().filter(|c| c.status == status).count();
        summary.push(format!("{}: {count}", status.label()));
    }
    out.push_str(&summary.join(", "));
    out.push_str("\n\n");
    for status in Status::ALL {
        out.push_str("## ");
        out.push_str(status.label());
        out.push_str("\n\n");
        out.push_str("| ID | Title | Owner | Updated | Notes |\n");
        out.push_str("|---|---|---|---|---|\n");
        let mut empty = true;
        for card in cards.iter().filter(|c| c.status == status) {
            empty = false;
            out.push_str(&row(card));
        }
        if empty {
            out.push_str("| | _No cards_ | | | |\n");
        }
        out.push('\n');
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// The board for a terminal: a heading per column (only `only`, when given) and a line per card.
pub fn render_text(cards: &[Card], only: Option<Status>) -> String {
    let mut out = String::new();
    for status in Status::ALL {
        if only.is_some_and(|s| s != status) {
            continue;
        }
        let column: Vec<&Card> = cards.iter().filter(|c| c.status == status).collect();
        out.push_str(&format!("{} ({})\n", status.label(), column.len()));
        if column.is_empty() {
            out.push_str("  (empty)\n");
        }
        for card in column {
            out.push_str(&format!(
                "  {:04}  {}{}\n",
                card.id,
                card.title,
                details(card)
            ));
        }
        out.push('\n');
    }
    out
}

/// What follows the title of a card in the terminal: owner, day of the last change, notes.
fn details(card: &Card) -> String {
    let mut parts: Vec<String> = Vec::new();
    if !card.owner.is_empty() {
        parts.push(card.owner.clone());
    }
    parts.push(format!("updated {}", card.updated));
    let notes = card.notes();
    if notes > 0 {
        let word = if notes == 1 { "note" } else { "notes" };
        parts.push(format!("{notes} {word}"));
    }
    format!("  ({})", parts.join(", "))
}

/// Days since 1970-01-01 to the (year, month, day) of the civil calendar, proleptic Gregorian.
/// The algorithm is Howard Hinnant's `civil_from_days`.
fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    (year, month, day)
}

/// A Unix time as the day (`2026-11-26`) and the time stamp of a note (`2026-11-26 10:40 UTC`).
pub fn date_time(unix_secs: u64) -> (String, String) {
    let secs = i64::try_from(unix_secs).unwrap_or(0);
    let (year, month, day) = civil_from_days(secs.div_euclid(86_400));
    let in_day = secs.rem_euclid(86_400);
    let date = format!("{year:04}-{month:02}-{day:02}");
    let stamp = format!(
        "{date} {:02}:{:02} UTC",
        in_day / 3_600,
        in_day % 3_600 / 60
    );
    (date, stamp)
}

/// The Unix time now.
fn now() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_secs())
}

/// A commit subject: at most [`MAX_SUBJECT_CHARS`] characters, no full stop or space at the end.
fn commit_subject(text: &str) -> String {
    let mut subject: String = text.chars().take(MAX_SUBJECT_CHARS).collect();
    while subject.ends_with('.') || subject.ends_with(' ') {
        subject.pop();
    }
    subject
}

/// What the user asked for.
#[derive(Debug, PartialEq, Eq)]
pub enum Command {
    /// Print the board, or one column of it.
    List { status: Option<Status> },
    /// Print one card.
    Show { id: u32 },
    /// Add a card.
    Add {
        title: String,
        status: Status,
        owner: Option<String>,
        note: Option<String>,
        commit: bool,
    },
    /// Move a card to another column.
    Move {
        id: u32,
        status: Status,
        commit: bool,
    },
    /// Append a note to a card.
    Note { id: u32, text: String, commit: bool },
    /// Delete a card.
    Remove { id: u32, commit: bool },
    /// Write `BOARD.md` again.
    Board,
    /// Verify the cards and the board.
    Check,
}

impl Command {
    /// Whether the change is to be committed.
    fn wants_commit(&self) -> bool {
        match self {
            Self::Add { commit, .. }
            | Self::Move { commit, .. }
            | Self::Note { commit, .. }
            | Self::Remove { commit, .. } => *commit,
            _ => false,
        }
    }
}

/// The words and options of one command line.
struct Parsed {
    /// Everything that is not an option, in order.
    words: Vec<String>,
    /// The options that take a value, as given.
    values: Vec<(String, String)>,
    /// The options without a value, as given.
    flags: Vec<String>,
}

impl Parsed {
    /// The value of an option, the last one when it is given twice.
    fn value(&self, name: &str) -> Option<String> {
        self.values
            .iter()
            .rev()
            .find(|(n, _)| n == name)
            .map(|(_, v)| v.clone())
    }

    /// Whether an option without a value is given.
    fn flag(&self, name: &str) -> bool {
        self.flags.iter().any(|f| f == name)
    }
}

/// Splits arguments into words and the options named in `with_value` and `flags`.
fn split(args: &[String], with_value: &[&str], flags: &[&str]) -> Result<Parsed, String> {
    let mut parsed = Parsed {
        words: Vec::new(),
        values: Vec::new(),
        flags: Vec::new(),
    };
    let mut args = args.iter();
    while let Some(arg) = args.next() {
        if with_value.contains(&arg.as_str()) {
            let value = args.next().ok_or_else(|| format!("{arg} needs a value"))?;
            parsed.values.push((arg.clone(), value.clone()));
        } else if flags.contains(&arg.as_str()) {
            parsed.flags.push(arg.clone());
        } else if arg.starts_with("--") {
            return Err(format!("unknown option '{arg}'"));
        } else {
            parsed.words.push(arg.clone());
        }
    }
    Ok(parsed)
}

/// A card number: `7`, `0007` or `#7`.
fn parse_id(word: &str) -> Result<u32, String> {
    word.trim_start_matches('#')
        .parse::<u32>()
        .map_err(|_| format!("'{word}' is not a card number"))
}

/// A column named on the command line.
fn parse_status(word: &str) -> Result<Status, String> {
    Status::parse(word).ok_or_else(|| {
        format!("unknown status '{word}': use backlog, in-progress, done or in-evaluation")
    })
}

/// Reads the arguments after `kanban`. No argument prints the board.
///
/// # Errors
/// On an unknown command or option, a missing word or value, or a number or status that is wrong.
pub fn parse_args(args: &[String]) -> Result<Command, String> {
    let Some((name, rest)) = args.split_first() else {
        return Ok(Command::List { status: None });
    };
    match name.as_str() {
        "list" | "ls" => match rest {
            [] => Ok(Command::List { status: None }),
            [word] => Ok(Command::List {
                status: Some(parse_status(word)?),
            }),
            _ => Err("list takes at most one argument: a status".to_string()),
        },
        "show" => match rest {
            [id] => Ok(Command::Show { id: parse_id(id)? }),
            _ => Err("show needs one argument: the card number".to_string()),
        },
        "add" => parse_add(rest),
        "move" | "mv" => parse_move(rest),
        "note" => parse_note(rest),
        "rm" | "remove" => parse_remove(rest),
        "board" if rest.is_empty() => Ok(Command::Board),
        "board" => Err("board takes no arguments".to_string()),
        "check" if rest.is_empty() => Ok(Command::Check),
        "check" => Err("check takes no arguments".to_string()),
        other => Err(format!("unknown kanban command '{other}'")),
    }
}

/// The arguments of `add`.
fn parse_add(rest: &[String]) -> Result<Command, String> {
    let parsed = split(rest, &["--status", "--owner", "--note"], &["--commit"])?;
    if parsed.words.is_empty() {
        return Err("add needs a title, for example: kanban add Fix the crash".to_string());
    }
    let status = parsed
        .value("--status")
        .map_or(Ok(Status::Backlog), |word| parse_status(&word))?;
    Ok(Command::Add {
        title: parsed.words.join(" "),
        status,
        owner: parsed.value("--owner"),
        note: parsed.value("--note"),
        commit: parsed.flag("--commit"),
    })
}

/// The arguments of `move`.
fn parse_move(rest: &[String]) -> Result<Command, String> {
    let parsed = split(rest, &[], &["--commit"])?;
    match parsed.words.as_slice() {
        [id, status] => Ok(Command::Move {
            id: parse_id(id)?,
            status: parse_status(status)?,
            commit: parsed.flag("--commit"),
        }),
        _ => Err("move needs two arguments: the card number and the status".to_string()),
    }
}

/// The arguments of `note`.
fn parse_note(rest: &[String]) -> Result<Command, String> {
    let parsed = split(rest, &[], &["--commit"])?;
    match parsed.words.split_first() {
        Some((id, text)) if !text.is_empty() => Ok(Command::Note {
            id: parse_id(id)?,
            text: text.join(" "),
            commit: parsed.flag("--commit"),
        }),
        _ => Err("note needs the card number and the text of the note".to_string()),
    }
}

/// The arguments of `rm`.
fn parse_remove(rest: &[String]) -> Result<Command, String> {
    let parsed = split(rest, &[], &["--commit"])?;
    match parsed.words.as_slice() {
        [id] => Ok(Command::Remove {
            id: parse_id(id)?,
            commit: parsed.flag("--commit"),
        }),
        _ => Err("rm needs one argument: the card number".to_string()),
    }
}

/// The folder of the cards.
fn cards_dir(root: &Path) -> PathBuf {
    root.join(DIR).join(CARDS)
}

/// The file of card `id`.
fn card_path(root: &Path, id: u32) -> PathBuf {
    cards_dir(root).join(card_file_name(id))
}

/// Reads one card.
fn load_card(root: &Path, id: u32) -> Result<Card, String> {
    let path = card_path(root, id);
    let text = match fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == ErrorKind::NotFound => {
            return Err(format!("there is no card {id:04}"));
        }
        Err(e) => return Err(format!("{}: {e}", path.display())),
    };
    parse_card(id, &text).map_err(|e| format!("{DIR}/{CARDS}/{}: {e}", card_file_name(id)))
}

/// Reads every card, by number. A missing folder is an empty board.
///
/// # Errors
/// When a file cannot be read, is not a card, or is not named by its number (`0007.md`).
pub fn load_cards(root: &Path) -> Result<Vec<Card>, String> {
    let dir = cards_dir(root);
    let entries = match fs::read_dir(&dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(format!("{}: {e}", dir.display())),
    };
    let mut cards = Vec::new();
    for entry in entries.flatten() {
        let file_name = entry.file_name().to_string_lossy().into_owned();
        let Some(id) = id_from_file_name(&file_name) else {
            continue;
        };
        if file_name != card_file_name(id) {
            return Err(format!(
                "{DIR}/{CARDS}/{file_name}: the file must be named {}",
                card_file_name(id)
            ));
        }
        cards.push(load_card(root, id)?);
    }
    cards.sort_by_key(|c| c.id);
    Ok(cards)
}

/// Writes the file of a card, and the folder when it is not there yet.
fn save_card(root: &Path, card: &Card) -> Result<(), String> {
    let dir = cards_dir(root);
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let path = card_path(root, card.id);
    fs::write(&path, render_card(card)).map_err(|e| format!("{}: {e}", path.display()))
}

/// Writes `BOARD.md` for these cards.
fn write_board(root: &Path, cards: &[Card]) -> Result<(), String> {
    let dir = root.join(DIR);
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let path = dir.join(BOARD);
    fs::write(&path, render_board(cards)).map_err(|e| format!("{}: {e}", path.display()))
}

/// Reads every card again and writes `BOARD.md`: the last step of every change.
fn refresh_board(root: &Path) -> Result<(), String> {
    let cards = load_cards(root)?;
    write_board(root, &cards)
}

/// What is wrong with the board, one line each; empty when it is in order. A repository that has
/// no card and no `BOARD.md` yet is in order.
///
/// # Errors
/// When `BOARD.md` exists but cannot be read.
pub fn problems(root: &Path) -> Result<Vec<String>, String> {
    let cards = match load_cards(root) {
        Ok(cards) => cards,
        Err(why) => return Ok(vec![why]),
    };
    let path = root.join(DIR).join(BOARD);
    let hint = "run `cargo tools kanban board`";
    match fs::read_to_string(&path) {
        Ok(text) if text.replace("\r\n", "\n") == render_board(&cards) => Ok(Vec::new()),
        Ok(_) => Ok(vec![format!("{DIR}/{BOARD} is out of date: {hint}")]),
        Err(e) if e.kind() == ErrorKind::NotFound && cards.is_empty() => Ok(Vec::new()),
        Err(e) if e.kind() == ErrorKind::NotFound => {
            Ok(vec![format!("{DIR}/{BOARD} is missing: {hint}")])
        }
        Err(e) => Err(format!("{}: {e}", path.display())),
    }
}

/// What a command did.
struct Outcome {
    /// What to tell the user.
    text: String,
    /// The subject of the commit for `--commit`; `None` when nothing was changed.
    subject: Option<String>,
    /// Whether `check` found a problem.
    failed: bool,
}

impl Outcome {
    /// A command that changed nothing.
    fn info(text: String) -> Self {
        Self {
            text,
            subject: None,
            failed: false,
        }
    }

    /// A command that changed the board.
    fn changed(text: String, subject: String) -> Self {
        Self {
            text,
            subject: Some(commit_subject(&subject)),
            failed: false,
        }
    }
}

/// Does what the command says in the repository at `root`. `now_secs` is the time and `user` the
/// name of the person (may be empty): both are parameters so that tests control them.
fn apply(root: &Path, command: &Command, now_secs: u64, user: &str) -> Result<Outcome, String> {
    let (date, stamp) = date_time(now_secs);
    match command {
        Command::List { status } => {
            let cards = load_cards(root)?;
            Ok(Outcome::info(render_text(&cards, *status)))
        }
        Command::Show { id } => Ok(Outcome::info(render_card(&load_card(root, *id)?))),
        Command::Board => {
            let cards = load_cards(root)?;
            write_board(root, &cards)?;
            Ok(Outcome::info(format!(
                "Wrote {DIR}/{BOARD} ({} cards).\n",
                cards.len()
            )))
        }
        Command::Check => {
            let found = problems(root)?;
            if found.is_empty() {
                return Ok(Outcome::info("The kanban board is in order.\n".to_string()));
            }
            let mut text = String::new();
            for problem in &found {
                text.push_str("  ");
                text.push_str(problem);
                text.push('\n');
            }
            Ok(Outcome {
                text,
                subject: None,
                failed: true,
            })
        }
        Command::Add {
            title,
            status,
            owner,
            note,
            ..
        } => {
            let id = next_id(&load_cards(root)?);
            let owner = owner.as_deref().unwrap_or(user);
            let mut card = new_card(id, title, *status, owner, &date)?;
            if let Some(text) = note {
                add_note(&mut card, &stamp, owner, text)?;
            }
            save_card(root, &card)?;
            refresh_board(root)?;
            Ok(Outcome::changed(
                format!("Added card {id:04} to {}: {}\n", status.label(), card.title),
                format!("Add kanban card {id:04}: {}", card.title),
            ))
        }
        Command::Move { id, status, .. } => {
            let mut card = load_card(root, *id)?;
            if card.status == *status {
                return Ok(Outcome::info(format!(
                    "Card {id:04} is already in {}.\n",
                    status.label()
                )));
            }
            let from = card.status;
            card.status = *status;
            card.updated = date;
            let text = format!("Moved from {} to {}", from.label(), status.label());
            add_note(&mut card, &stamp, user, &text)?;
            save_card(root, &card)?;
            refresh_board(root)?;
            Ok(Outcome::changed(
                format!("Card {id:04} moved to {}.\n", status.label()),
                format!("Move kanban card {id:04} to {}", status.label()),
            ))
        }
        Command::Note { id, text, .. } => {
            let mut card = load_card(root, *id)?;
            add_note(&mut card, &stamp, user, text)?;
            card.updated = date;
            save_card(root, &card)?;
            refresh_board(root)?;
            Ok(Outcome::changed(
                format!("Added a note to card {id:04}.\n"),
                format!("Add note to kanban card {id:04}"),
            ))
        }
        Command::Remove { id, .. } => {
            load_card(root, *id)?;
            let path = card_path(root, *id);
            fs::remove_file(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            refresh_board(root)?;
            Ok(Outcome::changed(
                format!("Deleted card {id:04}.\n"),
                format!("Remove kanban card {id:04}"),
            ))
        }
    }
}

/// Commits what changed under `kanban/`, and nothing else that may be staged.
fn commit(root: &Path, subject: &str) -> Result<(), String> {
    git(root, &["add", "--all", "--", DIR])?;
    git(root, &["commit", "--message", subject, "--", DIR])?;
    Ok(())
}

/// Runs a command in the repository at `root` and says what it did.
///
/// # Errors
/// When a card cannot be read or written, the card does not exist, an argument is wrong, or Git
/// refuses the commit of `--commit`. A failed `check` is not an error: it exits with failure.
pub fn run(root: &Path, command: &Command) -> Result<ExitCode, String> {
    let user = git(root, &["config", "user.name"]).unwrap_or_default();
    let outcome = apply(root, command, now(), &user)?;
    if outcome.failed {
        eprint!("{}", outcome.text);
        return Ok(ExitCode::FAILURE);
    }
    print!("{}", outcome.text);
    if command.wants_commit()
        && let Some(subject) = &outcome.subject
    {
        commit(root, subject)?;
        println!("Committed: {subject}");
    }
    Ok(ExitCode::SUCCESS)
}

